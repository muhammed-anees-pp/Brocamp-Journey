b = " Hello, World!"

# Length
print(len(b))

# Slicing
print(b[2:5])

# Upper case
print(b.upper())

# lower case
print(b.lower())

# Remove white space
print(b.strip())

# Split 
print(b.split(","))

# Concatenation
a = "Anees"
b = " P P"
c = a + b
print(c)

